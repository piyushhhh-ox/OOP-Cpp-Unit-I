#include <iostream>              // Includes the input/output library
using namespace std;             // Allows use of cout and endl directly

int main() {                     // Main function where program execution begins

    int roll = 101;              // Declares an integer variable for roll number
    char grade = 'A';            // Declares a character variable for grade
    float fee = 12500.50;        // Declares a float variable for fee amount

    cout << "Roll No: " << roll << endl;   // Displays the roll number
    cout << "Grade: " << grade << endl;    // Displays the grade
    cout << "Fee: " << fee << endl;        // Displays the fee amount

    return 0;                    // Ends the program successfully
}
